#!/bin/sh
# Builds gamemodes/bobbahotel/gamemode/nitro/port.lua from the Nitro TypeScript in src/.
set -e
cd "$(dirname "$0")"
[ -d node_modules ] || npm ci --silent
# JavaScript treats 0 as false, Lua as true: every condition must be a real true/false first
node test/truthiness.js
npx tstl -p tsconfig.json 2>&1 | grep -v "might generate duplicate code" || true
OUT=../../gamemodes/bobbahotel/gamemode/nitro/port.lua
{
	echo "-- GENERATED by tools/nitro-port (TypeScriptToLua). Do not edit: change tools/nitro-port/src and run build.sh."
	echo "-- Parts of Nitro (github.com/billsonnn/nitro-renderer, GPL-3): room geometry, room camera, planes on screen."
	echo "-- tools/nitro-port/test.sh checks this file gives exactly Nitro's results."
	sed 's/^return require("Port", \.\.\.)$/BOBBA.nitro = require("Port", ...)/' out/nitro.lua
} > "$OUT"
grep -q '^BOBBA.nitro = require("Port", ...)$' "$OUT"
echo "built $OUT"

# The avatar renderer (avatar/: Nitro's avatar code, see avatar/README.md)
TRUTHY_NO_ANY=1 node test/truthiness.js avatar/tsconfig.json
(cd avatar && ../node_modules/.bin/tstl -p tsconfig.json 2>&1 | grep -v "might generate duplicate code" || true)
AOUT=../../gamemodes/bobbahotel/gamemode/nitro/avatar.lua
{
	echo "-- GENERATED by tools/nitro-port/avatar (TypeScriptToLua). Do not edit: change tools/nitro-port/avatar/src and run tools/nitro-port/build.sh."
	echo "-- Nitro's avatar renderer (github.com/billsonnn/nitro-renderer, GPL-3): which pictures make an avatar, where, mirrored, coloured."
	echo "-- tools/nitro-port/avatar/test checks this file gives exactly Nitro's results."
	sed 's/^return require("Avatar", \.\.\.)$/BOBBA.nitroAvatar = require("Avatar", ...)/' avatar/out/avatar.lua
} > "$AOUT"
grep -q '^BOBBA.nitroAvatar = require("Avatar", ...)$' "$AOUT"
echo "built $AOUT"

# The furniture visualizations (furni/: Nitro's furniture code, see furni/README.md)
TRUTHY_NO_ANY=1 node test/truthiness.js furni/tsconfig.json
(cd furni && ../node_modules/.bin/tstl -p tsconfig.json 2>&1 | grep -v "might generate duplicate code" || true)
FOUT=../../gamemodes/bobbahotel/gamemode/nitro/furni.lua
{
	echo "-- GENERATED by tools/nitro-port/furni (TypeScriptToLua). Do not edit: change tools/nitro-port/furni/src and run tools/nitro-port/build.sh."
	echo "-- Nitro's furniture visualizations (github.com/billsonnn/nitro-renderer, GPL-3): which pictures make a furni, where, animated."
	echo "-- tools/nitro-port/furni/test checks this file gives exactly Nitro's results."
	sed 's/^return require("Furni", \.\.\.)$/BOBBA.nitroFurni = require("Furni", ...)/' furni/out/furni.lua
} > "$FOUT"
grep -q '^BOBBA.nitroFurni = require("Furni", ...)$' "$FOUT"
echo "built $FOUT"
